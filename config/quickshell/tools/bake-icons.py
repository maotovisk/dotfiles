#!/usr/bin/env python3
"""Dev-time only: bake assets/lucide/*.svg into common/Lucide.js.
Drop a new Lucide svg into assets/lucide/ and rerun this; the shell never runs it."""
import json, os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "assets", "lucide")
out = {}
for f in sorted(os.listdir(src)):
    if f.endswith(".svg"):
        s = re.sub(r"<!--.*?-->", "", open(os.path.join(src, f)).read(), flags=re.S)
        out[f[:-4]] = re.sub(r"\s+", " ", re.search(r"<svg[^>]*>(.*)</svg>", s, re.S).group(1)).strip()

with open(os.path.join(root, "common", "Lucide.js"), "w") as fh:
    fh.write(".pragma library\n\n// Lucide icon bodies (ISC license), generated by tools/bake-icons.py.\n"
             "// Rendered by components/Icon.qml as a data URI with the stroke colour injected.\n\nvar paths = ")
    fh.write(json.dumps(out, indent=1, ensure_ascii=False))
    fh.write('\n\nfunction svg(name, color, stroke) {\n    var body = paths[name] || paths["x"]\n'
             '    return "<svg xmlns=\\"http://www.w3.org/2000/svg\\" width=\\"24\\" height=\\"24\\" viewBox=\\"0 0 24 24\\" fill=\\"none\\" stroke=\\""'
             ' + color + "\\" stroke-width=\\"" + stroke + "\\" stroke-linecap=\\"round\\" stroke-linejoin=\\"round\\">" + body + "</svg>"\n}\n')
print(len(out), "icons")
